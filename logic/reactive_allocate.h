#ifndef REACTIVE_ALLOCATE_H
#define REACTIVE_ALLOCATE_H


/************************************************************
 * PCS额定视在功率
 ************************************************************/
#define PCS_RATED_S_NORMAL_KVA       2500.0f
#define PCS_RATED_S_HALF_KVA         1250.0f
#define PCS_RATED_S_ZERO_KVA         0.0f


/************************************************************
 * BMS状态
 *
 * BMS状态=3：
 * 对应PCS禁止参与无功
 ************************************************************/
#define BMS_STATE_STANDBY            3u


/************************************************************
 * PCS功率等级
 *
 * ZERO：
 *      bit0和bit1同时为1
 *      PCS可用容量=0
 *
 * HALF：
 *      bit0或者bit1单独为1
 *      PCS可用容量=1250
 *
 * FULL：
 *      bit0、bit1都为0
 *      PCS可用容量=2500
 ************************************************************/
#define PCS_POWER_LEVEL_ZERO         0u
#define PCS_POWER_LEVEL_HALF         1u
#define PCS_POWER_LEVEL_FULL         2u


/************************************************************
 * PCS无功相关信息
 ************************************************************/
typedef struct
{
    /********************************************************
     * PCS运行状态
     ********************************************************/
    uint16_t run;

    /********************************************************
     * PCS故障状态
     ********************************************************/
    uint16_t fault;


    /********************************************************
     * 一台PCS对应两个BMS
     ********************************************************/
    uint16_t bms1_state;
    uint16_t bms2_state;


    /********************************************************
     * PCS当前有功功率
     *
     * 单位：kW
     *
     * 内部采用float进行计算
     ********************************************************/
    float p_kw;


    /********************************************************
     * PCS当前有效额定视在功率
     *
     * 2500 / 1250 / 0
     ********************************************************/
    float rated_s_kva;


    /********************************************************
     * 当前PCS功率等级
     *
     * PCS_POWER_LEVEL_ZERO
     * PCS_POWER_LEVEL_HALF
     * PCS_POWER_LEVEL_FULL
     ********************************************************/
    uint16_t power_level;

} PCS_Q_Info;


/************************************************************
 * MV无功控制最终结果
 *
 * 按照之前要求：
 * 对外全部使用uint16_t
 ************************************************************/
typedef struct
{
    /********************************************************
     * 最终Group无功指令
     *
     * 正无功：
     *      直接使用正数
     *
     * 负无功：
     *      按int16_t补码存放在uint16_t中
     ********************************************************/
    uint16_t group1_q_cmd;
    uint16_t group2_q_cmd;


    /********************************************************
     * 两个Group当前最大允许无功
     ********************************************************/
    uint16_t group1_q_max;
    uint16_t group2_q_max;


    /********************************************************
     * 两个绕组共同允许最大无功
     ********************************************************/
    uint16_t balance_q_max;


    /********************************************************
     * 当前Group真正可以参与无功的PCS数量
     *
     * 0 / 1 / 2
     ********************************************************/
    uint16_t group1_q_available_num;
    uint16_t group2_q_available_num;

} MV_Q_Result;



void MV_ReactivePowerControl_A(
        uint16_t total_q_cmd,

        uint16_t master1_p,
        uint16_t slave1_p,

        uint16_t master2_p,
        uint16_t slave2_p,

        MV_Q_Result *result);
#endif